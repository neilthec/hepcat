"""Compare native HEPCAT QED SPINAS exports to the publication's signed Feynman amplitudes.

Example:
    python3 replay-signed.py --publication /path/to/hepcat-publication \
        --projects /path/to/generated-projects --spinas /path/to/spinas \
        --output /path/to/output

The projects directory contains physical/ and spurious/, each with eeAA/, eeee/,
eeAAA/, eeeeA/, eeAAAA/, eeeeAA/, and eeeeee/ generated by the native exporter.
Use a long-double ABI build of SPINAS. On ARM64 macOS this has 53 significand bits.
"""

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile

FAMILIES = ("eeAA", "eeee", "eeAAA", "eeeeA", "eeAAAA", "eeeeAA", "eeeeee")
PREFIX = "tests/benchmarks/reproduction/100k/catalog/"


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--publication", required=True, type=Path)
    parser.add_argument("--projects", required=True, type=Path)
    parser.add_argument("--spinas", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--family", choices=FAMILIES, action="append")
    parser.add_argument("--points", type=int, default=100000)
    parser.add_argument("--cxx", default="c++")
    args = parser.parse_args()
    if args.points < 1:
        parser.error("--points must be a positive integer")
    return args


def run_family(args, family, reference, share_source, driver, library):
    failure_count = 0
    with tempfile.TemporaryDirectory() as name:
        work = Path(name)
        original = work / "original"
        original.mkdir()
        for source in ("process.hpp", "process.cpp"):
            (original / source).write_bytes(reference.read(f"feynman/{family}/{source}"))
        source_dir = original
        if family == "eeAAAA":
            source_dir = work / "shared"
            source_dir.mkdir()
            helper = work / "share-feynman.py"
            helper.write_bytes(share_source)
            subprocess.run([sys.executable, str(helper), str(original), str(source_dir)], check=True)

        (work / "feynman-sig.hpp").write_bytes((source_dir / "process.hpp").read_bytes())
        feynman = (source_dir / "process.cpp").read_text()
        (work / "feynman.cpp").write_text(feynman.replace('#include "process.hpp"', '#include "feynman-sig.hpp"'))
        feynman_obj = work / "feynman.o"
        common_flags = [args.cxx, "-std=c++17", "-O2", "-DWITH_LONG_DOUBLE",
                         "-I" + str(args.spinas.resolve() / "include"), "-I" + str(work)]
        for policy in ("physical", "spurious"):
            native = args.projects.resolve() / policy / family
            if (native / "spinas" / "process.cpp").is_file():
                native /= "spinas"
            flags = common_flags + ["-I" + str(native)]
            if not feynman_obj.exists():
                subprocess.run(flags + ["-c", str(work / "feynman.cpp"), "-o", str(feynman_obj)], check=True)
            executable = work / ("signed-" + policy)
            subprocess.run(flags + ["-DCONSTRUCTIVE_PROCESS=" + family,
                "-DFEYNMAN_PROCESS=fd" + family, str(driver), str(native / "process.cpp"),
                str(feynman_obj), str(library), "-o", str(executable)], check=True)
            destination = args.output / policy / family
            destination.mkdir(parents=True, exist_ok=True)
            with (destination / "scores.csv").open("w") as out:
                subprocess.run([str(executable), str(args.points)], stdout=out, check=True)
            provenance = {"generated_source_sha256": hashlib.sha256((native / "process.cpp").read_bytes()).hexdigest(),
                          "generated_header_sha256": hashlib.sha256((native / "process.hpp").read_bytes()).hexdigest(),
                          "reference_source_sha256": hashlib.sha256((original / "process.cpp").read_bytes()).hexdigest(),
                          "seed": 861811, "points": args.points}
            (destination / "inputs.json").write_text(json.dumps(provenance, indent=2) + "\n")
            with (destination / "scores.csv").open() as results:
                rows = list(csv.DictReader(results))
            failed = sum(int(row["tensor_outliers"]) + int(row["nonfinite"]) for row in rows)
            print(policy, family, "tensor failures or nonfinite components:", failed, flush=True)
            failure_count += failed
            if failed:
                print("Inspect the raw event diagnostics and precision before interpreting this result.", file=sys.stderr)
    return failure_count


def main():
    args = parse_args()
    library = args.spinas.resolve() / "build" / "libspinas.a"
    if not library.exists():
        library = args.spinas.resolve() / "libspinas.a"
    if not library.is_file():
        raise SystemExit("Could not locate the SPINAS static library")
    driver = Path(__file__).resolve().with_name("signed.cpp")
    with zipfile.ZipFile(args.publication / "tests/benchmarks/benchmarks.zip") as archive:
        helper = archive.read(PREFIX + "share-feynman.py")
        generated = io.BytesIO(archive.read(PREFIX + "generated-sources.zip"))
    with zipfile.ZipFile(generated) as sources:
        failures = sum(run_family(args, family, sources, helper, driver, library)
                       for family in args.family or FAMILIES)
    return int(failures != 0)


if __name__ == "__main__":
    sys.exit(main())
